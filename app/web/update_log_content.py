    "## 📅 2025年12月23日 - LLM 意图识别问题解决方案",
    "",
    "### 🐛 问题修复",
    "",
    "#### 🔴 修复 LLM 意图识别返回 UNKNOWN 的问题",
    "",
    "**问题描述**：",
    "用户输入消息时，LLM 意图识别返回 \"UNKNOWN\" 而不是正确的意图类型（如 \"GREETING\"），导致消息显示为红色错误样式，而不是正常的聊天气泡样式。前端控制台显示 `intent: \"UNKNOWN\"`，导致意图处理逻辑无法正确执行。",
    "",
    "**根本原因分析**：",
    "后端接收到的 LLM 响应格式与预期格式不匹配：",
    "",
    "1. **LLM 平台返回格式正确**：",
    "   - 阿里云百炼平台返回的格式是正确的：`{\"intent_type\": \"GREETING\", \"content_to_process\": \"...\"}`",
    "   - LLM 平台配置正确，APP_ID 和 API_KEY 指向正确的应用",
    "",
    "2. **后端处理格式转换问题**：",
    "   - 后端的 `intent_recognizer.py` 中的 `_normalize_intent_data()` 函数将格式转换成了错误的格式",
    "   - 转换后的格式：`{\"intent\": \"UNKNOWN\", \"content\": \"...\"}`",
    "   - 这导致前端无法正确识别意图类型",
    "",
    "3. **字段映射不匹配**：",
    "   - 后端期望：`intent_data.get(\"intent\")`",
    "   - LLM 返回的是：`intent_data.get(\"intent_type\")`",
    "   - 后端在处理时优先查找 `intent` 字段，导致无法找到正确的意图类型",
    "",
    "**解决方案**：",
    "",
    "1. **添加格式转换函数**：",
    "   - 在 `api_server.py` 中添加 `normalize_llm_response()` 函数",
    "   - 将 LLM 返回的格式转换为前端期望的格式",
    "   - 处理字段映射：`intent_type` → `intent`，`content_to_process` → `content`",
    "   - 保留原始意图类型：`original_intent` 字段",
    "   - 特殊处理：如果 `intent_type` 是 `UNKNOWN` 但内容包含问候关键词，自动转换为 `GREETING`",
    "",
    "2. **在 API 端点中使用转换函数**：",
    "   - 在 `/api/chat` 端点中，调用 `intent_recognizer.recognize()` 后立即调用 `normalize_llm_response()`",
    "   - 确保 LLM 响应在后续处理前已被正确转换",
