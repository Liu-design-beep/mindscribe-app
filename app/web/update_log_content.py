    "### 🐛 问题修复",
    "",
    "#### 🔴 修复语音输入提示框被遮挡的问题",
    "",
    "**问题描述**：",
    "语音输入按钮的提示框（小窗）会被试用模式面板和连接状态指示器遮挡，导致用户无法看到提示内容。",
    "",
    "**根本原因**：",
    "语音输入提示框使用 `position: absolute`，受父元素（footer）的堆叠上下文限制，即使设置了较高的 `z-index`，仍然会被其他固定定位的元素遮挡。",
    "",
    "**解决方案**：",
    "",
    "1. **CSS 样式调整**：",
    "   - 将 `.voice-btn-tooltip` 的 `position` 从 `absolute` 改为 `fixed`",
    "   - 将 `z-index` 从 `10000` 提高到 `10001`，确保高于试用模式面板（1000）和连接状态指示器（1001）",
    "",
    "2. **JavaScript 位置计算**：",
    "   - 添加了 `updateTooltipPosition()` 函数，动态计算提示框位置",
    "   - 使用 `getBoundingClientRect()` 获取按钮的实际位置",
    "   - 在 `mouseenter` 时更新位置并显示提示框",
    "   - 添加了窗口大小改变和滚动事件监听器，确保位置始终正确",
    "",
    "**技术细节**：",
    "- `position: fixed` 使提示框脱离父元素的堆叠上下文，不受 footer 的 z-index 限制",
    "- `z-index: 10001` 确保提示框在所有其他元素之上",
    "- 动态位置计算确保提示框始终在按钮上方正确位置",
    "- 响应式更新确保窗口大小改变或滚动时位置正确",
    "",
    "**修改的文件**：",
    "- `程序/frontend/style.css` - 调整语音输入提示框的定位和 z-index",
    "- `程序/frontend/app.js` - 添加动态位置计算逻辑",
